"""Prepare the firmware's model and exact librosa frontend constants.

Run after `dvc pull` or the quantization/evaluation stages. This does not train
or promote models. Unsupported feature configurations fail before writing.
"""
import hashlib
import json
from pathlib import Path

import librosa
import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
FIRMWARE = ROOT / "firmware/esp32-sense"
EXPECTED = dict(type="logmel", n_mels=40, n_fft=512, hop_length=320,
                fmin=50, fmax=8000, log_offset=1e-6)


def frontend_tables():
    mel = librosa.filters.mel(sr=16000, n_fft=512, n_mels=40, fmin=50, fmax=8000)
    starts, ends, weights = [], [], []
    for row in mel:
        indices = np.flatnonzero(row)
        start, end = int(indices[0]), int(indices[-1]) + 1
        starts.append(start)
        ends.append(end)
        weights.extend(row[start:end])
    arrays = {
        "kHann": librosa.filters.get_window("hann", 512, fftbins=True),
        "kCos": np.cos(2 * np.pi * np.arange(256) / 512),
        "kSin": np.sin(2 * np.pi * np.arange(256) / 512),
        "kMelWeights": weights,
    }
    lines = ["// Generated by src/prepare_esp32_model.py; do not edit.",
             "#pragma once", "namespace doorbell {"]
    for name, values in arrays.items():
        # Scientific notation ensures even zero is a valid C++ float literal.
        kind = "float" if name == "kMelWeights" else "double"
        vals = ([f"{v:.9e}f" for v in np.asarray(values, dtype=np.float32)]
                if kind == "float" else [f"{v:.17e}" for v in values])
        lines.append(f"constexpr {kind} {name}[] = {{")
        lines.extend("  " + ", ".join(vals[i:i+6]) + "," for i in range(0, len(vals), 6))
        lines.append("};")
    for name, values in [("kMelStart", starts), ("kMelEnd", ends)]:
        lines.append(f"constexpr unsigned {name}[] = {{" + ", ".join(map(str, values)) + "};")
    lines.append("} // namespace doorbell\n")
    return "\n".join(lines)


def validate_configuration(params):
    from features import extractor_config
    if (params["training"]["head"] != "cnn" or params["chunk_size"] != 2000
            or extractor_config(params["feature_extraction"]) != EXPECTED):
        raise ValueError("ESP32 firmware requires the 2-second 40x100 logmel CNN configuration")


def prepare():
    from features import verify_feature_config
    from tflite_utils import write_c_array, C_ARRAY_VAR
    import tensorflow as tf

    if Path.cwd() != ROOT:
        raise ValueError("Run preparation from the repository root")
    params = yaml.safe_load((ROOT / "params.yaml").read_text())
    validate_configuration(params)
    verify_feature_config(ROOT / params["feature_extraction"]["features_dir"], params["feature_extraction"])
    model = (ROOT / "models/export/doorbell_int8.tflite").read_bytes()
    interpreter = tf.lite.Interpreter(model_content=model)
    interpreter.allocate_tensors()
    inp, out = interpreter.get_input_details()[0], interpreter.get_output_details()[0]
    if (list(inp["shape"]) != [1, 40, 100, 1] or list(out["shape"]) != [1, 1]
            or inp["dtype"] != np.int8 or out["dtype"] != np.int8):
        raise ValueError("Expected int8 [1,40,100,1] input and [1,1] output")
    # Re-evaluate locally: a metrics JSON alone cannot prove it describes
    # these exact bytes. This deliberately does not contact/promote MLflow.
    from dataset import load_dataset
    from evaluate_quantized import score_pair, gate_passed
    from tflite_utils import build_export_model
    X, y, _, _, _ = load_dataset(params)
    trained = tf.keras.models.load_model(ROOT / "models/trained/cnn_model.keras")
    stats = np.load(ROOT / "models/trained/cnn_normalization.npz")
    export_model = build_export_model(trained, stats["mean"], stats["std"])
    metrics, detail = score_pair(export_model, model, X, y)
    if not np.isfinite(metrics["f1_drop"]) or not gate_passed(metrics["f1_drop"], params["quantization"]["max_f1_drop"]):
        raise ValueError("Quantization evaluation gate failed for the firmware model")
    target = FIRMWARE / "lib/doorbell_model"
    target.mkdir(parents=True, exist_ok=True)
    write_c_array(model, target / "doorbell_model_data.cc", C_ARRAY_VAR)
    # Flash-resident test windows exercise the actual TFLM/ESP-NN backend
    # on every boot, before enabling live detections.
    scores = detail["int8_score"]
    rows = [int(np.argmin(scores)), int(np.argmax(scores))]
    vectors, expected = [], []
    for row in rows:
        scale, zero = inp["quantization"]
        q = np.clip(np.round(X[row] / scale + zero), -128, 127).astype(np.int8)
        interpreter.set_tensor(inp["index"], q[np.newaxis])
        interpreter.invoke()
        expected.append(int(interpreter.get_tensor(out["index"])[0, 0]))
        vectors.append("{" + ",".join(map(str, q.ravel().tolist())) + "}")
    (target / "model_self_test.h").write_text(
        "// Generated by prepare_esp32_model.py\n#pragma once\n#include <cstdint>\n"
        + "constexpr int8_t kModelTestInputs[2][4000] = {\n" + ",\n".join(vectors) + "};\n"
        + "constexpr int kModelTestOutputs[2] = {" + ",".join(map(str, expected)) + "};\n")
    table_path = FIRMWARE / "lib/doorbell_frontend/frontend_tables.h"
    table_path.write_text(frontend_tables())
    source_paths = ["params.yaml", "models/export/doorbell_int8.tflite",
                    "models/trained/cnn_model.keras", "models/trained/cnn_normalization.npz",
                    "firmware/esp32-sense/lib/doorbell_frontend/frontend_tables.h"]
    hashes = {path: hashlib.sha256((ROOT / path).read_bytes()).hexdigest() for path in source_paths}
    for path in [target / "doorbell_model_data.cc", target / "doorbell_model_data.h", target / "model_self_test.h"]:
        hashes[str(path.relative_to(ROOT))] = hashlib.sha256(path.read_bytes()).hexdigest()
    (target / "model_manifest.json").write_text(json.dumps({
        "sha256": hashlib.sha256(model).hexdigest(), "bytes": len(model),
        "source_sha256": hashes, "f1_drop": metrics["f1_drop"],
        "features": EXPECTED, "sample_rate": 16000,
        "input_quantization": inp["quantization"], "output_quantization": out["quantization"],
    }, indent=2) + "\n")
    print(f"Prepared {len(model)} byte model: {hashlib.sha256(model).hexdigest()}")


if __name__ == "__main__":
    prepare()
